import { chromium, newCtx, text, BASE } from "./ulib.mjs";
import { readFileSync } from "node:fs";
const C = JSON.parse(readFileSync("/tmp/qc3e/p8c.json", "utf8"));
const b = await chromium.launch({ headless: true });
const { ctx, page } = await newCtx(b, "teacher"); await ctx.addInitScript((c) => localStorage.setItem("ep:ui:course", c), C.A);
await page.goto(`${BASE}/documents?course=${C.A}`); await page.waitForTimeout(3500);
console.log((await text(page)).slice(0, 1800));
console.log(await page.evaluate(() => [...document.querySelectorAll("button,input,select,[role=switch],[role=checkbox],a")].slice(0, 60).map((e) => `${e.tagName}|${e.getAttribute("role") || e.type || ""}|${(e.getAttribute("aria-label") || e.innerText || e.name || "").slice(0, 40)}`).join("\n")));
await page.screenshot({ path: "/tmp/qc3e/ui/p6_docs.png" });
const { page: p2 } = await newCtx(b, "sv.gioi"); await p2.goto(`${BASE}/library?course=${C.A}`); await p2.waitForTimeout(3000);
console.log("--- LIB\n" + (await text(p2)).slice(0, 1200));
await b.close();
