# Đợt R · F4 Hỏi bài công khai (AI trả lời cần RAG → không kiểm được với embedding giả; kiểm tường lửa, kiểm duyệt, tường thuật nhánh «AI không đủ tin cậy»)
from rlib import *
import time
c1 = C("sv.kha"); tag = str(int(time.time()))[-5:]
c, pre, _ = api("sv.kha", "POST", f"/courses/{c1}/threads/precheck", {"title": "Hỏi về MSSV 20229002", "body": "Em là Bùi Thanh Khai MSSV 20229002, điểm của em sai."})
ok("R-F4-01 precheck phát hiện PII (MSSV, tên)", c == 200 and pre.get("allowed") is False and any(r["type"] == "MSSV" for r in pre.get("reasons", [])), f"{c} {str(pre)[:140]}")
c, j, _ = api("sv.kha", "POST", f"/courses/{c1}/threads", {"title": "Hỏi về MSSV 20229002", "body": "Em là Bùi Thanh Khai MSSV 20229002, điểm của em sai.", "redact": False})
ok("R-F4-02 đăng bài có PII bị chặn (tường lửa)", c == 422 and "PII" in str(j).upper(), f"{c} {str(j)[:160]}")
c, j, _ = api("sv.kha", "POST", f"/courses/{c1}/threads", {"title": f"QC-R {tag}: khác nhau giữa worm và virus", "body": "Cho em hỏi worm khác virus ở điểm nào ạ?", "tags": ["tuần 5"], "week_no": 5})
ok("R-F4-03 đăng bài sạch", c in (200, 201), f"{c} {str(j)[:100]}")
tid = (j or {}).get("id") or ((j or {}).get("thread") or {}).get("id")
time.sleep(8)
c, jt, _ = api("sv.nguyco", "GET", f"/courses/{c1}/threads/{tid}") if tid else (0, None, 0)
ok("R-F4-04 SV khác thấy bài công khai", c == 200, f"{c} posts={len((jt or {}).get('posts', []))}")
ai = [p for p in (jt or {}).get("posts", []) if p.get("kind") == "AI" or p.get("author_kind") == "AI"] if isinstance(jt, dict) else []
ok("R-F4-05 AI trả lời kiểu Socratic (cần RAG) — hoặc không tự trả lời khi không đủ tin cậy", True, f"AI post: {len(ai)} (embedding giả: KHÔNG KIỂM ĐƯỢC đường có nguồn)")
c, jp, _ = api("sv.nguyco", "POST", f"/courses/{c1}/threads/{tid}/posts", {"body": "Worm tự lây lan còn virus cần vật chủ."}) if tid else (0, None, 0)
ok("R-F4-06 SV khác bình luận", c in (200, 201), f"{c} {str(jp)[:80]}")
pid = ((jp or {}).get("post") or jp or {}).get("id") if isinstance(jp, dict) else None
c0, jfp, _ = api("sv.nguyco", "POST", f"/courses/{c1}/threads/precheck", {"title": "Worm", "body": "Em nghĩ virus cần vật chủ."})
ok("R-F4-06b «Em nghĩ …» (ý kiến, không hỏi riêng) không bị coi là câu hỏi cá nhân", c0 == 200 and jfp.get("allowed") is True, f"{c0} {str(jfp)[:150]}")
c, jr, _ = api("sv.nguyco", "POST", f"/courses/{c1}/threads/{tid}/report", {"reason": "SPAM"}) if tid else (0, None, 0)
ok("R-F4-07 báo cáo bài", c in (200, 201, 204), f"{c} {str(jr)[:100]}")
c, jm, _ = api("teacher", "GET", f"/courses/{c1}/moderation/queue")
ok("R-F4-08 giảng viên thấy bài bị báo trong hàng kiểm duyệt", c == 200 and tid in str(jm), f"{c}")
_, jv0, _ = api("teacher", "GET", f"/courses/{c1}/threads/{tid}"); ver = ((jv0 or {}).get("thread") or {}).get("version", 1)
c, jh, _ = api("teacher", "POST", f"/courses/{c1}/threads/{tid}/hide", {"reason": "QC-R thử ẩn", "version": ver}) if tid else (0, None, 0)
ok("R-F4-09 giảng viên ẩn bài (kèm lý do)", c in (200, 204), f"{c} {str(jh)[:100]}")
c, jv, _ = api("sv.nguyco", "GET", f"/courses/{c1}/threads/{tid}")
ok("R-F4-10 sau ẩn, SV khác không thấy (404/ẩn)", c in (404, 403) or "hidden" in str(jv).lower(), f"{c} {str(jv)[:100]}")
c, jo, _ = api("sv.kha", "GET", f"/courses/{c1}/threads/{tid}")
ok("R-F4-11 người đăng thấy lý do ẩn", c == 200 and ("QC-R thử ẩn" in str(jo) or "hidden" in str(jo).lower()), f"{c} {str(jo)[:140]}")
_, jv1, _ = api("teacher", "GET", f"/courses/{c1}/threads/{tid}"); ver = ((jv1 or {}).get("thread") or {}).get("version", 1)
c, ju, _ = api("teacher", "POST", f"/courses/{c1}/threads/{tid}/unhide", {"version": ver}) if tid else (0, None, 0)
ok("R-F4-12 bỏ ẩn", c in (200, 204), f"{c}")
c, js, _ = api("sv.kha", "POST", f"/courses/{c1}/threads/similar-confirmed", {"q": "khác nhau giữa worm và virus"})
ok("R-F4-13 câu tương tự (cờ tắt → rỗng)", c == 200, f"{c} {str(js)[:80]}")
c, jd, _ = api("sv.kha", "DELETE", f"/courses/{c1}/threads/{tid}") if tid else (0, None, 0)
ok("R-F4-14 người đăng xoá bài của mình", c in (200, 204), f"{c}")
print("w2b done")
