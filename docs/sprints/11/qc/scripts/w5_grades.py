# Đợt R · làn 5: F10 Sổ điểm, F12 Luyện đề
from rlib import *
import json, time
c1 = C("teacher")
other = course("teacher", "761988")
c, st, _ = api("teacher", "GET", f"/courses/{c1}/grade-scheme/status")
ok("R-F10-01 lớp 761987: công thức đã xác nhận", c == 200 and "CONFIRMED" in json.dumps(st), f"{c} {str(st)[:140]}")
c, st2, _ = api("teacher", "GET", f"/courses/{other}/grade-scheme/status")
ok("R-F10-02 lớp chưa có quy chế: chưa xác nhận", c == 200 and "CONFIRMED" not in json.dumps(st2), f"{c} {str(st2)[:140]}")
c, gb2, _ = api("teacher", "GET", f"/courses/{other}/gradebook")
ok("R-F10-03 chưa xác nhận công thức → sổ điểm khoá (không tính)", c in (409, 422, 403) or (c == 200 and not (gb2.get("rows") or gb2.get("items"))), f"{c} {str(gb2)[:140]}")
c, gb, _ = api("teacher", "GET", f"/courses/{c1}/gradebook")
ok("R-F10-04 sổ điểm GV (trọng số, dòng SV)", c == 200, f"{c} keys={list(gb.keys()) if isinstance(gb, dict) else gb}")
rows = gb.get("rows") or gb.get("items") or []
c, sv, _ = api("sv.kha", "GET", f"/courses/{c1}/gradebook")
ok("R-F10-05 SV không đọc sổ điểm của lớp (403)", c == 403, f"{c}")
c, me, _ = api("sv.kha", "GET", f"/courses/{c1}/me/grades")
ok("R-F10-06 SV thấy điểm đã công bố của mình", c == 200, f"{c} {str(me)[:200]}")
c, wi, _ = api("sv.kha", "POST", f"/courses/{c1}/me/grades/what-if", {"scores": {}})
ok("R-F10-07 what-if (tính bằng code, không LLM)", c in (200, 422), f"{c} {str(wi)[:160]}")
uid = (rows[0].get("student") or rows[0])["id"] if rows else None
if uid:
    c, ex, _ = api("teacher", "GET", f"/courses/{c1}/gradebook/students/{uid}/explain")
    ok("R-F10-08 giải thích điểm tổng (từng thành phần)", c == 200, f"{c} {str(ex)[:160]}")
    c, hs, _ = api("teacher", "GET", f"/courses/{c1}/gradebook/students/{uid}/history")
    ok("R-F10-09 lịch sử sửa điểm", c == 200, f"{c} {str(hs)[:100]}")
c, x, _ = api("teacher", "GET", f"/courses/{c1}/gradebook/export.xlsx")
ok("R-F10-10 xuất XLSX", c == 200, f"{c}")
c, pv, _ = api("teacher", "GET", f"/courses/{c1}/gradebook/preview")
ok("R-F10-11 xem trước trước khi chốt", c == 200, f"{c} {str(pv)[:160]}")
c, fz, _ = api("ta", "POST", f"/courses/{c1}/gradebook/finalize", {})
ok("R-F10-12 TA không chốt sổ (403)", c == 403, f"{c}")
c, fz, _ = api("teacher", "POST", f"/courses/{c1}/gradebook/finalize", {})
ok("R-F10-13 GV chốt sổ → snapshot", c in (200, 201), f"{c} {str(fz)[:200]}")
c, sn, _ = api("teacher", "GET", f"/courses/{c1}/gradebook/snapshots")
ok("R-F10-14 danh sách snapshot", c == 200 and len(sn.get("items", [])) >= 1, f"{c} {str(sn)[:160]}")
c, ge, _ = api("teacher", "PUT", f"/courses/{c1}/grade-entries", {"entries": []})
ok("R-F10-15 sổ đã chốt: sửa điểm bị chặn / không hợp lệ", c in (409, 422, 423), f"{c} {str(ge)[:140]}")
c, ul, _ = api("teacher", "POST", f"/courses/{c1}/gradebook/unlock", {"reason": "QC-R mở lại để kiểm tra"})
ok("R-F10-16 mở khoá phải kèm lý do", c in (200, 201), f"{c} {str(ul)[:140]}")
c, ul2, _ = api("teacher", "POST", f"/courses/{c1}/gradebook/unlock", {})
ok("R-F10-17 mở khoá không lý do bị từ chối", c in (409, 422), f"{c} {str(ul2)[:100]}")
print("w5 done")
